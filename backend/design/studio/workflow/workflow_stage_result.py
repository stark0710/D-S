"""
WorkflowStageResult Subsystem

Purpose:
    Defines the `WorkflowStageResult` domain model representing execution output of a single workflow stage step.

Role in Architecture:
    `WorkflowStageResult` encapsulates stage name, success status, ISO 8601 start/completion timestamps, duration,
    warnings, errors, artifacts, and diagnostic metadata.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any


def _current_timestamp() -> str:
    """Helper returning current UTC ISO 8601 timestamp string."""
    return datetime.now(timezone.utc).isoformat()


@dataclass(slots=True)
class WorkflowStageResult:
    """
    Workflow stage execution diagnostic output.

    Attributes:
        stage_name (str): Unique name of the executed workflow stage.
        success (bool): True if stage completed successfully; False otherwise.
        started_at (str): ISO 8601 start timestamp string.
        completed_at (str): ISO 8601 completion timestamp string.
        duration (float): Stage execution duration in seconds.
        warnings (list[str]): Non-fatal warnings encountered during stage execution.
        errors (list[str]): Fatal or non-fatal error messages.
        artifacts (list[Any]): Design artifacts generated by this stage.
        metadata (dict[str, Any]): Additional execution diagnostic metadata.
    """

    stage_name: str
    success: bool
    started_at: str = field(default_factory=_current_timestamp)
    completed_at: str = field(default_factory=_current_timestamp)
    duration: float = 0.0
    warnings: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    artifacts: list[Any] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)
