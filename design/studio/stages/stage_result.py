"""
StageResult Subsystem

Purpose:
    Defines the `StageResult` domain model representing execution output returned by a `DesignStage`.

Role in Architecture:
    `StageResult` encapsulates stage name, success status, generated outputs dictionary, warnings, errors,
    execution time duration, and metadata.
"""

from dataclasses import dataclass, field
from typing import Any


@dataclass(slots=True)
class StageResult:
    """
    Execution output summary for a DesignStage step.

    Attributes:
        stage_name (str): Unique name of the executed stage step.
        success (bool): True if stage completed successfully; False otherwise.
        outputs (dict[str, Any]): Dictionary of outputs generated by this stage step.
        warnings (list[str]): Non-fatal warnings encountered during stage execution.
        errors (list[str]): Error messages encountered during stage execution.
        execution_time (float): Stage execution duration in seconds.
        metadata (dict[str, Any]): Additional execution diagnostic metadata.
    """

    stage_name: str
    success: bool
    outputs: dict[str, Any] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    execution_time: float = 0.0
    metadata: dict[str, Any] = field(default_factory=dict)
