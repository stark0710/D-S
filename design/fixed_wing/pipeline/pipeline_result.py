"""
Pipeline Result Model for Fixed-Wing Design Execution.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional, Any

from backend.design.fixed_wing.mission.mission_result import MissionResult
from backend.design.fixed_wing.configuration.configuration_result import ConfigurationResult
from backend.design.fixed_wing.wing.wing_result import WingResult
from backend.design.fixed_wing.airfoil.airfoil_result import AirfoilResult
from backend.design.fixed_wing.tail.tail_result import TailResult
from backend.design.fixed_wing.fuselage.fuselage_result import FuselageResult
from backend.design.fixed_wing.propulsion.propulsion_result import PropulsionResult
from backend.design.fixed_wing.avionics.avionics_result import AvionicsResult
from backend.design.fixed_wing.payload.payload_result import PayloadResult
from backend.design.fixed_wing.mass_properties.mass_result import MassResult
from backend.design.fixed_wing.flight_performance.flight_result import FlightResult
from backend.design.fixed_wing.verification.verification_result import VerificationResult

from backend.design.fixed_wing.pipeline.convergence import IterationRecord


class PipelineStatus(str, Enum):
    """Execution status codes for Fixed-Wing Design Pipeline."""
    SUCCESS = "SUCCESS"
    INVALID_REQUIREMENTS = "INVALID_REQUIREMENTS"
    CONFIGURATION_INFEASIBLE = "CONFIGURATION_INFEASIBLE"
    SIZING_INFEASIBLE = "SIZING_INFEASIBLE"
    COMPONENT_SELECTION_FAILED = "COMPONENT_SELECTION_FAILED"
    NON_CONVERGED = "NON_CONVERGED"
    VERIFICATION_FAILED = "VERIFICATION_FAILED"
    
    # Phase 5B Hardened failure taxonomy
    AIRFOIL_STRUCTURE_INCOMPATIBLE = "AIRFOIL_STRUCTURE_INCOMPATIBLE"
    PAYLOAD_INFEASIBLE = "PAYLOAD_INFEASIBLE"
    PROPULSION_INFEASIBLE = "PROPULSION_INFEASIBLE"
    BATTERY_INFEASIBLE = "BATTERY_INFEASIBLE"
    COMMUNICATION_INFEASIBLE = "COMMUNICATION_INFEASIBLE"
    COMPONENT_DATABASE_LIMITATION = "COMPONENT_DATABASE_LIMITATION"
    MTOW_LIMIT_EXCEEDED = "MTOW_LIMIT_EXCEEDED"
    STABILITY_INFEASIBLE = "STABILITY_INFEASIBLE"
    PERFORMANCE_INFEASIBLE = "PERFORMANCE_INFEASIBLE"
    CONVERGENCE_FAILURE = "CONVERGENCE_FAILURE"
    VERIFICATION_FAILURE = "VERIFICATION_FAILURE"
    INTERNAL_EXCEPTION = "INTERNAL_EXCEPTION"


@dataclass
class FixedWingDesignResult:
    """
    Comprehensive output payload generated by FixedWingDesignPipeline.
    """
    success: bool
    status: PipelineStatus
    iterations: int
    converged: bool

    convergence_history: List[IterationRecord] = field(default_factory=list)

    mission_result: Optional[MissionResult] = None
    configuration_result: Optional[ConfigurationResult] = None
    construction_result: Optional[Any] = None
    wing_result: Optional[WingResult] = None
    airfoil_result: Optional[AirfoilResult] = None
    tail_result: Optional[TailResult] = None
    fuselage_result: Optional[FuselageResult] = None
    propulsion_result: Optional[PropulsionResult] = None
    avionics_result: Optional[AvionicsResult] = None
    payload_result: Optional[PayloadResult] = None
    mass_properties_result: Optional[MassResult] = None
    performance_result: Optional[FlightResult] = None
    verification_result: Optional[VerificationResult] = None
    electrical_result: Optional[Any] = None
    cg_result: Optional[Any] = None
    final_specification: Optional[Any] = None
    certification_report: Optional[Any] = None
    convergence_result: Optional[Any] = None
    pareto_front: Optional[Any] = None

    warnings: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)
